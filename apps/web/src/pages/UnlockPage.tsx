import { useEffect, useRef, useState } from "react";
import { Alert, Box, Button, Card, CardContent, CircularProgress, Stack, Typography } from "@mui/material";
import { useNavigate, useSearchParams } from "react-router-dom";

export default function UnlockPage() {
    const [searchParams] = useSearchParams();
    const navigate = useNavigate();
    const [error, setError] = useState("");
    const [loading, setLoading] = useState(false);
    const started = useRef(false);
    const code = searchParams.get("code");

    useEffect(() => {
        if (!code || started.current) return;
        started.current = true;
        let cancelled = false;

        async function redeem() {
            setLoading(true);
            setError("");
            try {
                const response = await fetch("/api/v1/auth/referee/redeem", {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({ code }),
                });
                const data = await response.json().catch(() => ({}));
                if (!response.ok) {
                    if (!cancelled) {
                        setError(data.error || "This QR code is invalid, expired, or already used.");
                        setLoading(false);
                    }
                    return;
                }
                if (cancelled) return;
                sessionStorage.setItem("referee_token", data.token);
                navigate("/referee", { replace: true });
            } catch (err) {
                if (!cancelled) {
                    setError(err instanceof Error ? err.message : "Could not redeem this QR code.");
                    setLoading(false);
                }
            }
        }

        void redeem();
        return () => { cancelled = true; };
    }, [code, navigate]);

    return (
        <Box sx={{ py: 5, display: "flex", justifyContent: "center" }}>
            <Card variant="outlined" sx={{ width: "100%", maxWidth: 520 }}>
                <CardContent sx={{ p: 3 }}>
                    <Stack spacing={2.5} sx={{ alignItems: "center" }}>
                        <Typography variant="h4" sx={{ fontWeight: 800 }}>Referee unlock</Typography>
                        {loading ? (
                            <>
                                <CircularProgress />
                                <Typography color="text.secondary">Verifying your single-use QR code…</Typography>
                            </>
                        ) : error ? (
                            <>
                                <Alert severity="error" sx={{ width: "100%" }}>{error}</Alert>
                                <Typography color="text.secondary" sx={{ textAlign: "center" }}>
                                    Ask the head referee to generate a new QR code. Codes expire after five minutes and can only be used once.
                                </Typography>
                                <Button variant="contained" onClick={() => navigate("/unlock", { replace: true })}>
                                    Return to unlock
                                </Button>
                            </>
                        ) : (
                            <>
                                <Typography color="text.secondary" sx={{ textAlign: "center" }}>
                                    Referee access requires a QR code generated by the head referee. Open the QR link on this device or scan the code with your device camera.
                                </Typography>
                                <Alert severity="info" sx={{ width: "100%" }}>
                                    QR codes expire after five minutes and can only be used once. If yours has expired, ask for a new one.
                                </Alert>
                            </>
                        )}
                    </Stack>
                </CardContent>
            </Card>
        </Box>
    );
}
